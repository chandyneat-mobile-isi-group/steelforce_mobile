class CategoryFacets {
  const CategoryFacets({
    required this.name,
    required this.sapSkuCount,
    required this.families,
    required this.brands,
    required this.grades,
    required this.sizes,
    required this.thicknessMm,
    required this.diameterMm,
    required this.widthMm,
    required this.colours,
    required this.units,
  });

  /// Category display name, matching [IsiDemoCatalog.categories].
  final String name;

  /// Distinct materials in this category in the SAP extract — the number the
  /// mock catalog is standing in for.
  final int sapSkuCount;

  /// SAP `Profile` (roofing) or `MaterialGroupName` (everything else) —
  /// whatever the category's family step picks from.
  final List<String> families;

  /// SAP `Brand`. A coating line on the roofing lines; a supplying mill on
  /// traded reinforcement; empty on K-Pipe, where SAP holds the literal "NA".
  final List<String> brands;

  /// SAP `Grade`. Substrate and coating weight in one string.
  final List<String> grades;

  /// SAP `Profile` read as a size code. Capped at 40 entries per category;
  /// the long tail is one-off cut sizes, not catalogue lines.
  final List<String> sizes;

  /// SAP `SaleThickness_mm` — the gauge the depot is quoted, which is not
  /// always `RawThickness_mm` (the coil it was formed from).
  final List<double> thicknessMm;

  /// Bar diameter, for traded reinforcement only. SAP stores it in the
  /// `SaleThickness_mm` column, but it is a diameter and belongs here.
  final List<double> diameterMm;

  /// SAP `Width_mm`: coil width for flat products, girth for folded ones.
  final List<double> widthMm;

  /// English half of SAP `TopColor`; the Khmer half is dropped here and kept
  /// in the demo rows' descriptions.
  final List<String> colours;

  /// SAP `BaseUnit`.
  final List<String> units;
}
